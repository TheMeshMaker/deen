"""Writes values-<lang>/strings.xml in every module from tools/i18n/<lang>.json.

English (values/) and Arabic (values-ar/) are written by hand and are not touched. Every other
language lives in one JSON file per language, keyed by string name, so a translator edits a
single file. Run from the repository root:

    python -I tools/i18n/export_strings.py    # refresh source.json from the English strings
    python -I tools/i18n/build_strings.py     # check every language and write the XML

The build stops on a missing key or a placeholder (%1$s, %d…) that differs from the English.
"""
import json
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.join(ROOT, "tools", "i18n")

# language file -> Android resource qualifier
LANGUAGES = {"ur": "ur", "id": "in", "tr": "tr", "bn": "bn", "fr": "fr"}

# Plural categories each language uses (CLDR). "many" in French is only for very large round
# numbers and reads like "other", so it is filled from "other" if missing.
PLURALS = {
    "fr": ["one", "many", "other"],
    "id": ["other"],
}
DEFAULT_PLURALS = ["one", "other"]

# Strings that are the same in every language (formats, names) may be left out of a language file.
SAME_EVERYWHERE = {
    "core_alarm_title", "feature_quran_surah_name", "feature_settings_voice_length",
    "feature_today_method_summary", "core_alarm_voice_aaqib", "feature_settings_src_cities_body",
}

PLACEHOLDER = re.compile(r"%(?:\d+\$)?[sd]")


def placeholders(text):
    return sorted(PLACEHOLDER.findall(text))


def escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def check(lang, key, english, translated):
    if isinstance(english, str):
        if not isinstance(translated, str) or not translated.strip():
            return f"{lang}: {key} is empty"
        if placeholders(english) != placeholders(translated):
            return f"{lang}: {key} placeholders {placeholders(translated)} != {placeholders(english)}"
    elif isinstance(english, list):
        if not isinstance(translated, list) or len(translated) != len(english):
            return f"{lang}: {key} needs {len(english)} items"
    else:
        if not isinstance(translated, dict):
            return f"{lang}: {key} must be a plural object"
        allowed = set(placeholders(english["other"]))
        for q, t in translated.items():
            if not set(placeholders(t)) <= allowed:
                return f"{lang}: {key}[{q}] has unknown placeholders"
    return None


def plural_items(lang, key, english, translated):
    items = []
    for q in PLURALS.get(lang, DEFAULT_PLURALS):
        t = translated.get(q)
        if t is None and q == "many":
            t = translated.get("other")
        if t is None and q == "other":
            t = translated.get("one")
        if t is None:
            raise SystemExit(f"{lang}: {key} is missing the '{q}' plural form")
        items.append((q, t))
    return items


def main():
    source = json.load(open(os.path.join(HERE, "source.json"), encoding="utf-8"))
    problems = []
    written = 0
    for lang, qualifier in LANGUAGES.items():
        path = os.path.join(HERE, f"{lang}.json")
        if not os.path.exists(path):
            problems.append(f"{lang}: no {lang}.json")
            continue
        strings = json.load(open(path, encoding="utf-8"))
        for module, entries in source.items():
            lines = ['<?xml version="1.0" encoding="utf-8"?>',
                     f"<!-- Generated by tools/i18n/build_strings.py from tools/i18n/{lang}.json. Edit that file, not this one. -->",
                     "<resources>"]
            for key, english in entries.items():
                translated = strings.get(key)
                if translated is None and (key in SAME_EVERYWHERE or not re.search(r"[^\W\d_]", PLACEHOLDER.sub("", english) if isinstance(english, str) else "x")):
                    translated = english
                if translated is None:
                    problems.append(f"{lang}: missing {key}")
                    continue
                problem = check(lang, key, english, translated)
                if problem:
                    problems.append(problem)
                    continue
                if isinstance(english, str):
                    lines.append(f'    <string name="{key}">{escape(translated)}</string>')
                elif isinstance(english, list):
                    lines.append(f'    <string-array name="{key}">')
                    lines += [f"        <item>{escape(t)}</item>" for t in translated]
                    lines.append("    </string-array>")
                else:
                    lines.append(f'    <plurals name="{key}">')
                    lines += [f'        <item quantity="{q}">{escape(t)}</item>' for q, t in plural_items(lang, key, english, translated)]
                    lines.append("    </plurals>")
            lines.append("</resources>")
            out_dir = os.path.join(ROOT, module, "src", "main", "res", f"values-{qualifier}")
            os.makedirs(out_dir, exist_ok=True)
            with open(os.path.join(out_dir, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
                f.write("\n".join(lines) + "\n")
            written += 1
        extra = set(strings) - {k for e in source.values() for k in e}
        if extra:
            print(f"{lang}: unused keys {sorted(extra)}")
    if problems:
        print("\n".join(problems))
        raise SystemExit(f"{len(problems)} problem(s)")
    print(f"ok: {written} files, {len(LANGUAGES)} languages")


if __name__ == "__main__":
    main()
